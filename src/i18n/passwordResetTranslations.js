export function usePasswordResetText() {
  const { language } = useLanguage()
  const selected = messages[language === 'sw' ? 'sw' : 'en']
  return (key, values = {}) => {
    const template = selected[key] ?? messages.en[key] ?? messages.en.request_failed
    return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''))
  }
}
