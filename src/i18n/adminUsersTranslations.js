export function useAdminUsersText() {
  const { language } = useLanguage()
  return (key, values = {}) => (text[key]?.[language === 'sw' ? 1 : 0] ?? key)
    .replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`))
}
