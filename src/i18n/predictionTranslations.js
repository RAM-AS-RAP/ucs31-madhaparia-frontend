export function usePredictionText() {
  const { language } = useLanguage()

  return (key, values = {}) => {
    const template = messages[language]?.[key] ?? messages.en[key] ?? key

    return template.replace(/\{(\w+)\}/g, (_, name) =>
      String(values[name] ?? `{${name}}`)
    )
  }
}
