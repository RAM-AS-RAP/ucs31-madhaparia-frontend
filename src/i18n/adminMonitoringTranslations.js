export function useAdminMonitoringText() {
  const { language } = useLanguage()
  return (key, values = {}) => (messages[key]?.[language === 'sw' ? 1 : 0] ?? key)
    .replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`))
}
